def write_csv():
    rows = []
    for (family, ratio, size), vals in sorted(MANUAL_PG.items(),
                                              key=lambda kv: (kv[0][0], kv[0][2], kv[0][1])):
        rows.append({
            "family": family, "size": size, "ratio_nominal": ratio,
            "p_gn_kw":  vals[0] if vals[0] is not None else "",
            "p_gf_kw":  vals[1] if vals[1] is not None else "",
            "p_gc_kw":  vals[2] if vals[2] is not None else "",
            "p_gfc_kw": vals[3] if vals[3] is not None else "",
        })
    out_path = ROOT / "data" / "thermal_power.csv"
    with open(out_path, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["family", "size", "ratio_nominal",
                                          "p_gn_kw", "p_gf_kw", "p_gc_kw", "p_gfc_kw"])
        w.writeheader()
        for r in rows:
            w.writerow(r)
    print(f"Wrote {out_path}  ({len(rows)} rows)")


if __name__ == "__main__":
    write_csv()
