def write_csv(path: Path, rows: list[dict], fieldnames: list[str]):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        for r in rows:
            w.writerow(r)
    print(f"  wrote {path.relative_to(ROOT)}  ({len(rows)} rows)")


def determine_stage(family: str, ratio_nominal: float, size: int) -> int:
    """根据 i_N 和系列家族判断级数(RKH1/2/3 或 RKB2/3)。"""
    if family == "RKH":
        if ratio_nominal <= 5.6:
            return 2 if size >= 7 else 1
        if ratio_nominal <= 22.4:
            return 2
        return 3
    if family == "RKB":
        return 3 if ratio_nominal >= 31.5 else 2
    raise ValueError(family)


def emit_ratio_torque():
    rows = []
    # RKH
    for ratio, t2n_list in RKH_T2N.items():
        ratio_actual_list = RKH_RATIO.get(ratio, [None] * len(RKH_SIZES))
        for size, t2n in zip(RKH_SIZES, t2n_list):
            if t2n is None:
                continue
            ratio_actual = ratio_actual_list[RKH_SIZES.index(size)] if RKH_RATIO.get(ratio) else None
            stage = determine_stage("RKH", ratio, size)
            rows.append({
                "family": "RKH",
                "stage": stage,
                "series_code": f"RKH{stage}",
                "size": size,
                "ratio_nominal": ratio,
                "ratio_actual": ratio_actual if ratio_actual is not None else "",
                "t2n_nm": int(round(t2n * 1000)),  # kN·m → N·m
            })
    # RKB
    for ratio, t2n_list in RKB_T2N.items():
        ratio_actual_list = RKB_RATIO.get(ratio, [None] * len(RKB_SIZES))
        for size, t2n in zip(RKB_SIZES, t2n_list):
            if t2n is None:
                continue
            ratio_actual = ratio_actual_list[RKB_SIZES.index(size)] if RKB_RATIO.get(ratio) else None
            stage = determine_stage("RKB", ratio, size)
            rows.append({
                "family": "RKB",
                "stage": stage,
                "series_code": f"RKB{stage}",
                "size": size,
                "ratio_nominal": ratio,
                "ratio_actual": ratio_actual if ratio_actual is not None else "",
                "t2n_nm": int(round(t2n * 1000)),
            })
    write_csv(
        DATA / "ratio_torque.csv",
        rows,
        ["family", "stage", "series_code", "size", "ratio_nominal", "ratio_actual", "t2n_nm"],
    )


